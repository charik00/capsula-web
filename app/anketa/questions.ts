export const QUESTIONNAIRES: Questionnaire[] = [SMOKING, SUGAR];

export function getQuestionnaire(key: string): Questionnaire | undefined {
  return QUESTIONNAIRES.find((q) => q.key === key);
}

// Плоский список вопросов для подстановки читаемых подписей в админке.
export function flatQuestions(key: string): Record<string, Question> {
  const q = getQuestionnaire(key);
  const map: Record<string, Question> = {};
  if (!q) return map;
  for (const s of q.sections)
    for (const item of s.questions) map[item.id] = item;
  return map;
}
